import { Injectable, NotFoundException } from '@nestjs/common';
import { PrismaService } from '../../database/prisma.service';
import { RegisterDocumentDto, ListDocumentsQueryDto, PresignUploadDto } from './dto/document.dto';
import { S3Util } from '../../common/utils/s3.util';

@Injectable()
export class DocumentsService {
  constructor(private prisma: PrismaService) {}

  /** Step 1 of the upload flow: get a presigned S3 PUT URL. The browser PUTs the file directly to S3, then calls register() with the returned fileUrl. */
  getUploadUrl(dto: PresignUploadDto) {
    return S3Util.createPresignedUpload(dto.fileName, dto.mimeType);
  }

  /**
   * Records metadata for a file already uploaded to S3 via a presigned URL
   * (generated by a not-yet-built `/documents/upload-url` endpoint in the
   * AWS Deployment phase). Keeping upload and registration separate avoids
   * routing large binaries through this API server.
   */
  register(dto: RegisterDocumentDto, uploadedById?: string) {
    return this.prisma.document.create({
      data: {
        type: dto.type,
        fileUrl: dto.fileUrl,
        fileName: dto.fileName,
        mimeType: dto.mimeType,
        farmer: dto.farmerId ? { connect: { id: dto.farmerId } } : undefined,
        entityType: dto.entityType,
        entityId: dto.entityId,
        uploadedById,
      },
    });
  }

  async getById(id: string) {
    const doc = await this.prisma.document.findUnique({ where: { id } });
    if (!doc) throw new NotFoundException('Document not found');
    return doc;
  }

  list(query: ListDocumentsQueryDto) {
    const page = Math.max(1, Number(query.page) || 1);
    const limit = Math.min(100, Math.max(1, Number(query.limit) || 20));
    const where = {
      ...(query.farmerId ? { farmerId: query.farmerId } : {}),
      ...(query.entityType ? { entityType: query.entityType } : {}),
      ...(query.entityId ? { entityId: query.entityId } : {}),
      ...(query.type ? { type: query.type } : {}),
    };

    return Promise.all([
      this.prisma.document.findMany({
        where,
        skip: (page - 1) * limit,
        take: limit,
        orderBy: { createdAt: 'desc' },
      }),
      this.prisma.document.count({ where }),
    ]).then(([items, total]) => ({ items, meta: { page, limit, total } }));
  }
}
